"""Build the full-page background map from Census TIGER/Line 2024 (CC0).

Usage: uv run --with pyshp python -I scripts/build-map.py RAW_DIR
RAW_DIR holds the unzipped TIGER folders: tl_2024_40_prisecroads, tl_2024_40143_roads,
tl_2024_40145_roads, tl_2024_40143_areawater, tl_2024_40145_areawater
(https://www2.census.gov/geo/tiger/TIGER2024/).

Writes public/map/streets.svg (faint street grid and water, loaded as an image) and
src/map-data.ts (highways, the ordered BA route, endpoints) in the same coordinate space.
"""

import json
import math
import pathlib
import sys

import shapefile

ROOT = pathlib.Path(__file__).resolve().parent.parent
RAW = pathlib.Path(sys.argv[1])
WEST, SOUTH, EAST, NORTH = -96.16, 35.88, -95.54, 36.46
K = math.cos(math.radians((SOUTH + NORTH) / 2))
S = 4000  # map units per degree of latitude
W, H = round((EAST - WEST) * K * S), round((NORTH - SOUTH) * S)
DOWNTOWN = (-95.983615, 36.144100)
BROKEN_ARROW = (-95.742998, 36.038320)


def xy(lon, lat):
    return ((lon - WEST) * K * S, (NORTH - lat) * S)


def inside(pts, pad=0.02):
    return any(WEST - pad <= x <= EAST + pad and SOUTH - pad <= y <= NORTH + pad for x, y in pts)


def simplify(pts, tol):
    if len(pts) < 3:
        return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1
    norm = math.hypot(dx, dy) or 1e-9
    far, idx = 0.0, 0
    for i in range(1, len(pts) - 1):
        d = abs(dy * (pts[i][0] - x1) - dx * (pts[i][1] - y1)) / norm
        if d > far:
            far, idx = d, i
    if far <= tol:
        return [pts[0], pts[-1]]
    return simplify(pts[: idx + 1], tol)[:-1] + simplify(pts[idx:], tol)


def d_attr(lines, tol, decimals=0, close=False):
    out = []
    for line in lines:
        pts = simplify([xy(*p) for p in line], tol)
        cmd, last = [], None
        for x, y in pts:
            p = (round(x, decimals), round(y, decimals))
            if p != last:
                cmd.append(f"{p[0]:g},{p[1]:g}")
                last = p
        if len(cmd) > 1:
            out.append("M" + "L".join(cmd) + ("Z" if close else ""))
    return "".join(out)


def parts(shape):
    idx = list(shape.parts) + [len(shape.points)]
    return [shape.points[idx[i] : idx[i + 1]] for i in range(len(idx) - 1)]


def read(name, keep):
    r = shapefile.Reader(str(RAW / name / f"{name}.shp"))
    fields = [f[0] for f in r.fields[1:]]
    for sr in r.iterShapeRecords():
        rec = dict(zip(fields, sr.record))
        if keep(rec):
            for p in parts(sr.shape):
                if inside(p):
                    yield p


highways = list(read("tl_2024_40_prisecroads", lambda r: True))
streets = []
for county in ("40143", "40145"):
    streets += read(f"tl_2024_{county}_roads", lambda r: r["MTFCC"] in ("S1200", "S1400"))
water = []
for county in ("40143", "40145"):
    water += read(f"tl_2024_{county}_areawater", lambda r: float(r["AWATER"]) > 400_000)

# The BA route, downtown to Broken Arrow, from the vetted segments in tulsa-roads.json. TIGER has
# both carriageways; these indices chain one of them end to end. Cut at the point nearest Broken Arrow.
segs = [list(map(tuple, s)) for s in json.loads((ROOT / "data" / "tulsa-roads.json").read_text())["ba"]]
route = [p for i in (2, 3, 8, 11) for p in segs[i]]
dist = lambda a, b: math.hypot((a[0] - b[0]) * K, a[1] - b[1])
cut = min(range(len(route)), key=lambda i: dist(route[i], BROKEN_ARROW))
route = route[: cut + 1]
print("route", route[0], route[-1], file=sys.stderr)

street_d = d_attr(streets, 1.2)
water_d = d_attr(water, 1.5, close=True)
(ROOT / "public" / "map" / "streets.svg").write_text(
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}">'
    f'<path d="{water_d}" fill="#fff" fill-opacity=".14"/>'
    f'<path d="{street_d}" fill="none" stroke="#fff" stroke-opacity=".16" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round"/>'
    "</svg>\n"
)

# Split the drawn route into stretches at the boundaries in src/config.ts (STRETCH_BOUNDARIES).
BOUNDARIES = [(-95.91248, 36.1157), (-95.8797, 36.1054), (-95.82737, 36.08532), (-95.77614, 36.0638)]
cuts = [min(range(len(route)), key=lambda i: dist(route[i], b)) for b in BOUNDARIES]
edges = [0] + cuts + [len(route) - 1]
stretch_d = [d_attr([route[edges[i] : edges[i + 1] + 1]], 0.6, 1) for i in range(len(edges) - 1)]

rx = [xy(*p) for p in route]
xs, ys = [p[0] for p in rx], [p[1] for p in rx]
data = {
    "width": W,
    "height": H,
    "highways": d_attr(highways, 0.8, 1),
    "route": d_attr([route], 0.6, 1),
    "stretches": stretch_d,
    "downtown": [round(v, 1) for v in xy(*DOWNTOWN)],
    "brokenArrow": [round(v, 1) for v in xy(*BROKEN_ARROW)],
    "corridor": [round(min(xs), 1), round(min(ys), 1), round(max(xs), 1), round(max(ys), 1)],
}
(ROOT / "src" / "map-data.ts").write_text(
    "// Generated by scripts/build-map.py from Census TIGER/Line 2024 (CC0). Do not edit by hand.\n"
    f"export const MAP = {json.dumps(data)} as const;\n"
)
print(f"{W}x{H}", file=sys.stderr)
